import { build } from 'esbuild';
import { mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const entries = [
  {
    entryPoint: join(repoRoot, 'serverless/entries/generations-seedance.ts'),
    outfile: join(repoRoot, 'api/generations/seedance.js'),
  },
  {
    entryPoint: join(repoRoot, 'serverless/entries/health-diagnostics.ts'),
    outfile: join(repoRoot, 'api/health/diagnostics.js'),
  },
];

for (const entry of entries) {
  await mkdir(dirname(entry.outfile), { recursive: true });
  await build({
    entryPoints: [entry.entryPoint],
    outfile: entry.outfile,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    packages: 'external',
    legalComments: 'none',
    banner: {
      js: '// Generated by scripts/build-vercel-api.mjs. Do not edit by hand.',
    },
  });
}

console.log('Built the self-contained Seedance and health diagnostics Vercel functions.');
