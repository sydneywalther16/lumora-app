import { build } from 'esbuild';
import { mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const entryPoint = join(repoRoot, 'serverless/entries/generations-seedance.ts');
const outfile = join(repoRoot, 'api/generations/seedance.js');

await mkdir(dirname(outfile), { recursive: true });
await build({
  entryPoints: [entryPoint],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  packages: 'external',
  legalComments: 'none',
  banner: {
    js: '// Generated by scripts/build-vercel-api.mjs. Do not edit by hand.',
  },
});

console.log('Built the self-contained Seedance Vercel function.');
